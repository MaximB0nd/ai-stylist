PRIVACY_NAV_ITEMS = tuple(
    (f"privacy-section-{index}", text)
    for index, text in enumerate(PRIVACY_BLOCKS)
    if text[:1].isdigit() and "." not in text.split(" ", 1)[0]
)


def _block_html(index, text):
    content = escape(text)
    if index == 0:
        return f'<h2 id="privacy-title">{content}</h2>'
    if text[:1].isdigit() and "." not in text.split(" ", 1)[0]:
        heading_id = f"privacy-section-{index}"
        return f'<h3 id="{heading_id}">{content}</h3>'
    return f'<p>{content}</p>'


def _policy_content():
    return "".join(_block_html(index, text) for index, text in enumerate(PRIVACY_BLOCKS[1:], start=1))


def _privacy_nav():
    links = "".join(
        f'<a href="#{heading_id}">{escape(label)}</a>'
        for heading_id, label in PRIVACY_NAV_ITEMS
    )
    return f"""
<nav class="privacy-anchor" aria-label="Разделы политики">
  <div>{links}</div>
</nav>
"""


def page():
    return app_shell(
        f"""
<section class="info-page privacy-page" aria-labelledby="privacy-title">
  <div class="info-hero privacy-hero">
    {_block_html(0, PRIVACY_BLOCKS[0])}
  </div>
  <div class="privacy-layout">
    <article class="privacy-document">
      {_policy_content()}
    </article>
    {_privacy_nav()}
  </div>
</section>
""",
        title="Политика",
        active_page="privacy",
    )
